//! OpenAPI 3.0/3.1 import and lossy 3.0 export.
//!
//! Import maps every operation of every path to a [`RequestDef`]: the first
//! server URL joined with the path becomes the request URL, `query`/`header`
//! parameters become rows, JSON request bodies are sampled from their schema
//! into a raw body, and security schemes are approximated as auth
//! placeholders. Operations carrying a first tag are grouped into a folder
//! named after the tag. Every approximation is recorded in the [`Report`].
//!
//! Export produces a minimal OpenAPI 3.0 document with one operation per
//! request (path + method + summary/description). The document itself
//! carries a comment noting that the export is lossy.

use std::collections::BTreeMap;

use serde_json::{json, Map, Value};

use restrust_core::model::{
    new_id, ApiKeyIn, AuthConfig, AuthKind, BodyKind, Collection, CollectionItem, Folder,
    HttpMethod, KeyValue, RequestBody, RequestDef,
};

use crate::{description_from, Imported, InterchangeError, Report};

const OPERATIONS: [(&str, HttpMethod); 7] = [
    ("get", HttpMethod::Get),
    ("post", HttpMethod::Post),
    ("put", HttpMethod::Put),
    ("patch", HttpMethod::Patch),
    ("delete", HttpMethod::Delete),
    ("head", HttpMethod::Head),
    ("options", HttpMethod::Options),
];

// --- public API ---------------------------------------------------------------

/// Parses `text` as JSON or YAML, verifies it is an OpenAPI 3.x document,
/// and imports it as one collection named from `info.title`. Swagger 2.0 is
/// rejected with a clear error.
pub fn detect_and_import(text: &str) -> Result<Imported, InterchangeError> {
    let doc = parse_document(text)?;
    import_document(&doc)
}

/// Exports a [`Collection`] as a minimal OpenAPI **3.0** YAML document
/// (lossy: only paths, methods, names and descriptions survive).
pub fn export_3_0(c: &Collection) -> Result<String, InterchangeError> {
    let mut paths: Map<String, Value> = Map::new();
    export_items(&c.items, &mut paths);
    let mut info = Map::new();
    info.insert("title".into(), json!(c.name));
    info.insert("version".into(), json!("1.0.0"));
    if let Some(d) = &c.description {
        info.insert("description".into(), json!(d));
    }
    let mut doc = Map::new();
    doc.insert("openapi".into(), json!("3.0.3"));
    doc.insert("info".into(), Value::Object(info));
    doc.insert("paths".into(), Value::Object(paths));
    let yaml = serde_yaml_ng::to_string(&Value::Object(doc)).map_err(|e| {
        InterchangeError::WithDetail {
            context: "OpenAPI 3.0 export failed".to_string(),
            message: e.to_string(),
        }
    })?;
    Ok(format!(
        "# Generated by restrust from collection '{}'.\n# Lossy export: only paths, methods, names and descriptions\n# survive; request bodies, parameters, auth and headers are not exported.\n{yaml}",
        c.name
    ))
}

// --- import --------------------------------------------------------------------

fn parse_document(text: &str) -> Result<Value, InterchangeError> {
    let trimmed = text.trim_start();
    if trimmed.starts_with('{') {
        serde_json::from_str(text)
            .map_err(|e| InterchangeError::BadInput(format!("invalid JSON: {e}")))
    } else {
        serde_yaml_ng::from_str(text)
            .map_err(|e| InterchangeError::BadInput(format!("invalid YAML: {e}")))
    }
}

fn import_document(doc: &Value) -> Result<Imported, InterchangeError> {
    if doc.get("swagger").is_some() {
        return Err(InterchangeError::UnsupportedFormat(
            "OpenAPI/Swagger 2.0 is not supported; convert the document to 3.0 or 3.1 first"
                .to_string(),
        ));
    }
    let Some(version) = doc.get("openapi").and_then(Value::as_str) else {
        return Err(InterchangeError::BadInput(
            "not an OpenAPI document: no 'openapi' field".to_string(),
        ));
    };
    if !version.starts_with("3.") {
        return Err(InterchangeError::UnsupportedFormat(format!(
            "OpenAPI version '{version}' is not supported (supported: 3.0.x and 3.1.x)"
        )));
    }
    let mut report = Report::default();
    if version
        .split('.')
        .nth(1)
        .and_then(|m| m.parse::<u8>().ok())
        .is_some_and(|m| m >= 2)
    {
        report.note_lossy(format!(
            "OpenAPI {version} document imported with 3.1 semantics, best effort"
        ));
    }

    let info = doc.get("info");
    let title = info
        .and_then(|i| i.get("title"))
        .and_then(Value::as_str)
        .unwrap_or("Imported OpenAPI")
        .to_string();
    let description = info.and_then(|i| description_from(i.get("description")));

    let base = doc
        .pointer("/servers/0/url")
        .and_then(Value::as_str)
        .unwrap_or_default()
        .trim_end_matches('/')
        .to_string();
    if base.contains('{') {
        report.note_lossy("server URL contains variables; imported verbatim");
    }
    if doc
        .get("servers")
        .and_then(Value::as_array)
        .is_some_and(|a| a.len() > 1)
    {
        let count = doc
            .get("servers")
            .and_then(Value::as_array)
            .map_or(0, |a| a.len());
        report.note_lossy(format!("{count} servers defined; only the first was used"));
    }
    if doc.get("webhooks").is_some() {
        report.note_unsupported("webhooks are not imported");
    }
    let schemes = doc
        .pointer("/components/securitySchemes")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();
    let default_security = doc.get("security");

    let Some(paths) = doc.get("paths").and_then(Value::as_object) else {
        return Err(InterchangeError::BadInput(
            "no 'paths' object found in OpenAPI document".to_string(),
        ));
    };

    let mut items: Vec<CollectionItem> = Vec::new();
    let mut folders: BTreeMap<String, Vec<CollectionItem>> = BTreeMap::new();
    let mut response_count = 0usize;

    for (path, path_item) in paths {
        let path_params = path_item
            .get("parameters")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        let Some(path_obj) = path_item.as_object() else {
            continue;
        };
        for (key, op) in path_obj {
            if matches!(
                key.as_str(),
                "parameters" | "summary" | "description" | "servers" | "$ref"
            ) {
                continue;
            }
            let Some((_, method)) = OPERATIONS.iter().find(|(name, _)| *name == key) else {
                if key == "trace" {
                    report.note_unsupported(format!(
                        "path '{path}': TRACE operations are not supported"
                    ));
                } else {
                    report.note_unsupported(format!(
                        "path '{path}': unsupported key '{key}' ignored"
                    ));
                }
                continue;
            };
            let Some(op) = op.as_object() else {
                continue;
            };
            response_count += op
                .get("responses")
                .and_then(Value::as_object)
                .map_or(0, |r| r.len());
            let request = request_from_operation(
                op,
                &path_params,
                path,
                *method,
                &base,
                &schemes,
                default_security,
                doc,
                &mut report,
            );
            let tag = op
                .get("tags")
                .and_then(Value::as_array)
                .and_then(|a| a.first())
                .and_then(Value::as_str)
                .map(str::to_string);
            match tag {
                Some(tag) => folders
                    .entry(tag)
                    .or_default()
                    .push(CollectionItem::Request(request)),
                None => items.push(CollectionItem::Request(request)),
            }
        }
    }

    if response_count > 0 {
        report.note_unsupported(format!(
            "{response_count} response definition(s) not imported (responses are not modeled)"
        ));
    }
    for (tag, tagged) in folders {
        items.push(CollectionItem::Folder(Folder {
            id: new_id(),
            name: tag,
            description: None,
            items: tagged,
            auth: None,
        }));
    }

    let collection = Collection {
        id: new_id(),
        name: title,
        description,
        // untagged requests first, then tag folders in deterministic order
        items,
        variables: Vec::new(),
        auth: None,
        events: Vec::new(),
    };
    Ok(Imported {
        collections: vec![collection],
        environments: Vec::new(),
        report,
    })
}

#[allow(clippy::too_many_arguments)]
fn request_from_operation(
    op: &Map<String, Value>,
    path_params: &[Value],
    path: &str,
    method: HttpMethod,
    base: &str,
    schemes: &Map<String, Value>,
    default_security: Option<&Value>,
    doc: &Value,
    report: &mut Report,
) -> RequestDef {
    let operation_id = op.get("operationId").and_then(Value::as_str);
    let summary = op.get("summary").and_then(Value::as_str);
    let name = operation_id
        .or(summary)
        .map(str::to_string)
        .unwrap_or_else(|| format!("{} {}", method.as_str(), path));

    let joined_path = if path.starts_with('/') {
        path.to_string()
    } else {
        format!("/{path}")
    };
    let url = if base.is_empty() {
        joined_path
    } else {
        format!("{base}{joined_path}")
    };

    // Operation parameters override path-level ones with the same name+in.
    let mut merged: Vec<Value> = path_params.to_vec();
    if let Some(op_params) = op.get("parameters").and_then(Value::as_array) {
        for p in op_params {
            let name_in = (
                p.get("name").and_then(Value::as_str),
                p.get("in").and_then(Value::as_str),
            );
            merged.retain(|existing| {
                (
                    existing.get("name").and_then(Value::as_str),
                    existing.get("in").and_then(Value::as_str),
                ) != name_in
            });
            merged.push(p.clone());
        }
    }

    let mut query = Vec::new();
    let mut headers = Vec::new();
    let mut path_param_names = Vec::new();
    for p in &merged {
        let Some(p) = p.as_object() else { continue };
        let pname = p.get("name").and_then(Value::as_str).unwrap_or_default();
        let pin = p.get("in").and_then(Value::as_str).unwrap_or_default();
        let value = p
            .get("schema")
            .map(|s| param_value(s, doc, &name, report))
            .unwrap_or_default();
        let row = KeyValue {
            key: pname.to_string(),
            value,
            enabled: p.get("required").and_then(Value::as_bool).unwrap_or(false),
            description: description_from(p.get("description")),
        };
        match pin {
            "query" => query.push(row),
            "header" => headers.push(row),
            "path" => path_param_names.push(pname.to_string()),
            "cookie" => report.note_unsupported(format!(
                "operation '{name}': cookie parameter '{pname}' is not supported"
            )),
            other => report.note_unsupported(format!(
                "operation '{name}': parameter location '{other}' is not supported"
            )),
        }
    }

    let body = op
        .get("requestBody")
        .map(|rb| body_from_request_body(rb, doc, &name, report))
        .unwrap_or_default();

    let security = op.get("security").or(default_security);
    let auth = security.and_then(|s| auth_from_security(s, schemes, &name, report));

    if op.get("deprecated").and_then(Value::as_bool) == Some(true) {
        report.note_unsupported(format!(
            "operation '{name}': 'deprecated' flag is not modeled"
        ));
    }
    if op.get("callbacks").is_some() {
        report.note_unsupported(format!("operation '{name}': callbacks are not imported"));
    }
    if op.get("servers").is_some() {
        report.note_lossy(format!(
            "operation '{name}': operation-level servers ignored; document server used"
        ));
    }

    let mut desc_parts: Vec<String> = Vec::new();
    if let Some(s) = summary {
        if s != name {
            desc_parts.push(s.to_string());
        }
    }
    if let Some(d) = description_from(op.get("description")) {
        desc_parts.push(d);
    }
    if !path_param_names.is_empty() {
        desc_parts.push(format!(
            "Path parameters: {} (substitute in the URL).",
            path_param_names.join(", ")
        ));
    }
    let description = (!desc_parts.is_empty()).then(|| desc_parts.join("\n\n"));

    RequestDef {
        id: new_id(),
        name,
        description,
        method,
        url,
        query,
        headers,
        body,
        auth,
    }
}

/// The sample value of a parameter: `default`/`example`/enum first, then a
/// shallow sample generated from the schema, rendered as a string.
fn param_value(schema: &Value, doc: &Value, ctx: &str, report: &mut Report) -> String {
    let sample = sample_from_schema(schema, doc, &mut Vec::new(), ctx, report);
    match sample {
        Value::String(s) => s,
        other => other.to_string(),
    }
}

fn body_from_request_body(rb: &Value, doc: &Value, ctx: &str, report: &mut Report) -> RequestBody {
    let Some(content) = rb.get("content").and_then(Value::as_object) else {
        report.note_unsupported(format!(
            "request '{ctx}': requestBody without a content map is not modeled"
        ));
        return RequestBody::default();
    };
    let chosen = content
        .get("application/json")
        .map(|m| ("application/json", m))
        .or_else(|| {
            content
                .iter()
                .find(|(k, _)| k.ends_with("+json"))
                .map(|(k, v)| (k.as_str(), v))
        })
        .or_else(|| {
            content
                .get("application/x-www-form-urlencoded")
                .map(|m| ("application/x-www-form-urlencoded", m))
        })
        .or_else(|| {
            content
                .get("multipart/form-data")
                .map(|m| ("multipart/form-data", m))
        })
        .or_else(|| {
            content
                .iter()
                .find(|(k, _)| k.starts_with("text/"))
                .map(|(k, v)| (k.as_str(), v))
        });
    let Some((mime, media)) = chosen else {
        report.note_unsupported(format!(
            "request '{ctx}': requestBody media types are not importable"
        ));
        return RequestBody::default();
    };
    if content.len() > 1 {
        report.note_lossy(format!(
            "request '{ctx}': requestBody has {} media types; only '{mime}' was imported",
            content.len()
        ));
    }
    let is_json = mime == "application/json" || mime.ends_with("+json");
    let schema_rows = |report: &mut Report| -> Vec<KeyValue> {
        media
            .get("schema")
            .and_then(|s| s.get("properties"))
            .and_then(Value::as_object)
            .map(|props| {
                props
                    .iter()
                    .map(|(k, s)| KeyValue {
                        key: k.clone(),
                        value: param_value(s, doc, ctx, report),
                        enabled: true,
                        description: description_from(s.get("description")),
                    })
                    .collect()
            })
            .unwrap_or_default()
    };
    if is_json {
        let sample = media
            .get("schema")
            .map(|s| sample_from_schema(s, doc, &mut Vec::new(), ctx, report))
            .unwrap_or_else(|| json!({}));
        let raw = serde_json::to_string_pretty(&sample).unwrap_or_else(|_| "{}".to_string());
        RequestBody {
            kind: BodyKind::Raw {
                mime: mime.to_string(),
            },
            raw: Some(raw),
            rows: Vec::new(),
        }
    } else if mime == "application/x-www-form-urlencoded" {
        RequestBody {
            kind: BodyKind::UrlEncoded,
            raw: None,
            rows: schema_rows(report),
        }
    } else if mime == "multipart/form-data" {
        RequestBody {
            kind: BodyKind::Multipart,
            raw: None,
            rows: schema_rows(report),
        }
    } else if mime.starts_with("text/") {
        RequestBody {
            kind: BodyKind::Raw {
                mime: mime.to_string(),
            },
            raw: Some(
                media
                    .get("example")
                    .and_then(Value::as_str)
                    .unwrap_or_default()
                    .to_string(),
            ),
            rows: Vec::new(),
        }
    } else {
        report.note_unsupported(format!(
            "request '{ctx}': media type '{mime}' bodies are not imported"
        ));
        RequestBody::default()
    }
}

fn auth_from_security(
    security: &Value,
    schemes: &Map<String, Value>,
    ctx: &str,
    report: &mut Report,
) -> Option<AuthConfig> {
    let requirements = security.as_array()?;
    if requirements.len() > 1 {
        report.note_lossy(format!(
            "request '{ctx}': {} security requirements; only the first applied",
            requirements.len()
        ));
    }
    let requirement = requirements.first()?.as_object()?;
    if requirement.len() > 1 {
        report.note_lossy(format!(
            "request '{ctx}': multiple security schemes required; only the first applied"
        ));
    }
    let (name, _) = requirement.iter().next()?;
    let scheme = schemes.get(name)?;
    match scheme
        .get("type")
        .and_then(Value::as_str)
        .unwrap_or_default()
    {
        "http" => match scheme
            .get("scheme")
            .and_then(Value::as_str)
            .unwrap_or_default()
        {
            "bearer" => {
                report.note_lossy(format!(
                    "request '{ctx}': security scheme '{name}' (http bearer) approximated as bearer auth with a placeholder token"
                ));
                Some(AuthConfig {
                    kind: AuthKind::Bearer {
                        token: "{{bearerToken}}".to_string(),
                    },
                })
            }
            "basic" => {
                report.note_lossy(format!(
                    "request '{ctx}': security scheme '{name}' (http basic) approximated as basic auth with placeholder credentials"
                ));
                Some(AuthConfig {
                    kind: AuthKind::Basic {
                        username: "{{username}}".to_string(),
                        password: "{{password}}".to_string(),
                    },
                })
            }
            other => {
                report.note_unsupported(format!(
                    "request '{ctx}': http auth scheme '{other}' (in '{name}') is not supported"
                ));
                None
            }
        },
        "apiKey" => {
            let add_to = if scheme.get("in").and_then(Value::as_str) == Some("query") {
                ApiKeyIn::Query
            } else {
                ApiKeyIn::Header
            };
            let key = scheme.get("name").and_then(Value::as_str).unwrap_or(name);
            report.note_lossy(format!(
                "request '{ctx}': security scheme '{name}' (apiKey) approximated as API-key auth with a placeholder value"
            ));
            Some(AuthConfig {
                kind: AuthKind::ApiKey {
                    key: key.to_string(),
                    value: "{{apiKey}}".to_string(),
                    add_to,
                },
            })
        }
        other => {
            report.note_unsupported(format!(
                "request '{ctx}': security scheme type '{other}' ('{name}') is not supported"
            ));
            None
        }
    }
}

// --- schema sampling ------------------------------------------------------------

/// Recursively builds an example JSON value from a schema: `example`/`default`
/// win, `$ref`s are followed inside the document, `object` samples its
/// properties, `array` yields one sampled item, scalars yield type-typical
/// values (or the first enum member). `oneOf`/`anyOf` sample the first
/// variant; `allOf` merges shallowly — each noted in the report.
fn sample_from_schema(
    schema: &Value,
    doc: &Value,
    refs: &mut Vec<String>,
    ctx: &str,
    report: &mut Report,
) -> Value {
    if let Some(example) = schema.get("example").filter(|v| !v.is_null()) {
        return example.clone();
    }
    if let Some(r) = schema.get("$ref").and_then(Value::as_str) {
        if refs.iter().any(|seen| seen == r) {
            report.note_lossy(format!(
                "request '{ctx}': circular $ref '{r}' sampled as {{}}"
            ));
            return json!({});
        }
        refs.push(r.to_string());
        let sampled = match resolve_pointer(doc, r) {
            Some(target) => sample_from_schema(target, doc, refs, ctx, report),
            None => {
                report.note_lossy(format!(
                    "request '{ctx}': unresolvable $ref '{r}' sampled as {{}}"
                ));
                json!({})
            }
        };
        refs.pop();
        return sampled;
    }
    if let Some(default) = schema.get("default").filter(|v| !v.is_null()) {
        return default.clone();
    }
    if let Some(first) = schema
        .get("oneOf")
        .or_else(|| schema.get("anyOf"))
        .and_then(Value::as_array)
        .and_then(|a| a.first())
    {
        report.note_lossy(format!(
            "request '{ctx}': oneOf/anyOf sampled using the first variant"
        ));
        return sample_from_schema(first, doc, refs, ctx, report);
    }
    if let Some(all) = schema.get("allOf").and_then(Value::as_array) {
        if all.len() > 1 {
            report.note_lossy(format!("request '{ctx}': allOf branches merged shallowly"));
        }
        let mut merged = Map::new();
        for sub in all {
            if let Value::Object(sampled) = sample_from_schema(sub, doc, refs, ctx, report) {
                merged.extend(sampled);
            }
        }
        if let Some(Value::Object(direct)) = schema.get("properties") {
            for (k, v) in direct {
                merged.insert(k.clone(), sample_from_schema(v, doc, refs, ctx, report));
            }
        }
        return Value::Object(merged);
    }
    let type_name = schema_type(schema);
    match type_name.as_deref() {
        Some("array") => match schema.get("items") {
            Some(s) => json!([sample_from_schema(s, doc, refs, ctx, report)]),
            None => json!([]),
        },
        Some("string") => enum_first(schema).unwrap_or_else(|| json!("string")),
        Some("integer") | Some("number") => enum_first(schema).unwrap_or_else(|| json!(0)),
        Some("boolean") => enum_first(schema).unwrap_or(json!(true)),
        Some("null") => Value::Null,
        Some("object") => object_sample(schema, doc, refs, ctx, report),
        None if schema.get("properties").is_some() => object_sample(schema, doc, refs, ctx, report),
        None => json!({}),
        Some(other) => {
            report.note_lossy(format!(
                "request '{ctx}': schema type '{other}' sampled as a string"
            ));
            json!("string")
        }
    }
}

fn enum_first(schema: &Value) -> Option<Value> {
    schema
        .get("enum")
        .and_then(Value::as_array)
        .and_then(|a| a.first())
        .cloned()
}

fn object_sample(
    schema: &Value,
    doc: &Value,
    refs: &mut Vec<String>,
    ctx: &str,
    report: &mut Report,
) -> Value {
    let mut obj = Map::new();
    if let Some(Value::Object(props)) = schema.get("properties") {
        for (k, s) in props {
            obj.insert(k.clone(), sample_from_schema(s, doc, refs, ctx, report));
        }
    }
    Value::Object(obj)
}

fn schema_type(schema: &Value) -> Option<String> {
    match schema.get("type") {
        Some(Value::String(s)) => Some(s.clone()),
        // 3.1 allows "type": ["string", "null"]
        Some(Value::Array(types)) => types
            .iter()
            .filter_map(Value::as_str)
            .find(|t| *t != "null")
            .map(str::to_string),
        _ => None,
    }
}

fn resolve_pointer<'a>(doc: &'a Value, pointer: &str) -> Option<&'a Value> {
    let path = pointer.strip_prefix("#/")?;
    let mut cur = doc;
    for raw in path.split('/') {
        let seg = raw.replace("~1", "/").replace("~0", "~");
        cur = cur.get(seg.as_str())?;
    }
    Some(cur)
}

// --- export ---------------------------------------------------------------------

fn export_items(items: &[CollectionItem], paths: &mut Map<String, Value>) {
    for item in items {
        match item {
            CollectionItem::Request(r) => {
                let path = url_path(&r.url);
                let entry = paths
                    .entry(path)
                    .or_insert_with(|| Value::Object(Map::new()));
                if let Value::Object(op_map) = entry {
                    let mut op = Map::new();
                    op.insert("summary".into(), json!(r.name));
                    if let Some(d) = &r.description {
                        op.insert("description".into(), json!(d));
                    }
                    op.insert(
                        "responses".into(),
                        json!({ "default": { "description": "" } }),
                    );
                    op_map.insert(r.method.as_str().to_ascii_lowercase(), Value::Object(op));
                }
            }
            CollectionItem::Folder(f) => export_items(&f.items, paths),
        }
    }
}

/// Extracts the URL path for the OpenAPI `paths` key. Uses the `url` crate
/// for absolute URLs (restoring `{param}` braces the url crate percent-
/// encodes), with a manual fallback for scheme-less URLs like
/// `{{base_url}}/things`.
fn url_path(url: &str) -> String {
    let no_fragment = url.split('#').next().unwrap_or(url);
    let no_query = no_fragment.split('?').next().unwrap_or(no_fragment);
    if let Ok(parsed) = url::Url::parse(no_query) {
        return parsed.path().replace("%7B", "{").replace("%7D", "}");
    }
    if let Some(pos) = no_query.find("://") {
        let rest = &no_query[pos + 3..];
        return rest
            .find('/')
            .map(|i| rest[i..].to_string())
            .unwrap_or_else(|| "/".to_string());
    }
    if no_query.starts_with('/') {
        no_query.to_string()
    } else {
        format!("/{no_query}")
    }
}
